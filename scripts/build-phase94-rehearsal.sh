#!/bin/sh
# Builds database/tests/phase94-rehearsal.sql = phase 94 (without its begin/commit) + database/tests/phase94-checks.sql,
# so the rehearsal always tests the exact migration. Run from the project folder: sh scripts/build-phase94-rehearsal.sh
set -e
out=database/tests/phase94-rehearsal.sql
{
  echo "-- Phase 94 rehearsal · tests the automatic delivery fee on the real database WITHOUT saving anything."
  echo "-- GENERATED by scripts/build-phase94-rehearsal.sh — edit phase94-delivery-fee-quotes.sql or tests/phase94-checks.sql instead."
  echo "--"
  echo "-- Run this whole file at once in the Supabase SQL editor. It applies phase 94, uses EXAMPLE rates (not real"
  echo "-- Lalamove rates) to place pretend orders, and ends with an error on purpose: that cancels everything."
  echo "-- Expected last line: ERROR: REHEARSAL REPORT (nothing was saved) … followed by PASS/FAIL for each check."
  echo
  echo "-- ===== phase 94 ====="
  grep -v -e '^begin;$' -e '^commit;$' -e "^notify pgrst" database/phase94-delivery-fee-quotes.sql
  echo
  echo "-- ===== checks ====="
  cat database/tests/phase94-checks.sql
} > "$out"
echo "wrote $out"
