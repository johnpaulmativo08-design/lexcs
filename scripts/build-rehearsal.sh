#!/bin/sh
# Builds database/tests/phaseNN-rehearsal.sql = [tests/phaseNN-setup.sql] + phase NN (without begin/commit/notify)
# + tests/phaseNN-checks.sql, so a rehearsal always tests the exact migration.
# Usage, from the project folder: sh scripts/build-rehearsal.sh 95
set -e
n="$1"; mig=$(ls database/phase"$n"-*.sql | head -1); out=database/tests/phase"$n"-rehearsal.sql
{
  echo "-- Phase $n rehearsal · tests $(basename "$mig") on the real database WITHOUT saving anything."
  echo "-- GENERATED by scripts/build-rehearsal.sh — edit the migration or tests/phase$n-*.sql instead."
  echo "-- Run this whole file at once in the Supabase SQL editor. It ends with an error on purpose: that cancels"
  echo "-- everything. Expected last line: ERROR: REHEARSAL REPORT (nothing was saved) … with PASS/FAIL for each check."
  echo
  if [ -f database/tests/phase"$n"-setup.sql ]; then echo "-- ===== setup ====="; cat database/tests/phase"$n"-setup.sql; echo; fi
  echo "-- ===== phase $n ====="
  grep -v -e '^begin;$' -e '^commit;$' -e "^notify pgrst" "$mig"
  echo
  echo "-- ===== checks ====="
  cat database/tests/phase"$n"-checks.sql
} > "$out"
echo "wrote $out"
